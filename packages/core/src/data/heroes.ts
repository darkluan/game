import type { AbilityAi, AbilityDef, HeroDef } from '../types.js';
import { seconds } from './balance.js';

const s3 = (a: number, b: number, c: number): number[] => [seconds(a), seconds(b), seconds(c)];
const same = (v: number): number[] => [v, v, v];

function ability(
  id: string,
  name: string,
  description: string,
  targeting: AbilityDef['targeting'],
  range: number,
  ai: AbilityAi,
  cooldownTicks: number[],
  cost: number[],
  params: Record<string, number[]>,
): AbilityDef {
  return { id, name, description, targeting, range, ai, cooldownTicks, cost, params, effect: id };
}

